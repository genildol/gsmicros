              <h2 class="entry-title">
                <a href="blog-single.html">A importância da qualidade dos dados</a>
              </h2>
              <p>
                Não basta possuir muitos dados. É necessário possuir <strong>dados confiáveis</strong>.
              </p>

              <p>
                Uma instituição pode ter milhões de registros armazenados em seus sistemas e, ainda assim,
                não conseguir produzir informações úteis para a gestão.
              </p>

              <p>
                Isso acontece quando existem cadastros duplicados, campos incompletos, informações incorretas,
                dados desatualizados, classificações inconsistentes ou registros realizados de maneira
                diferente por cada setor.
              </p>

              <ul>
                <li>Cadastros duplicados;</li>
                <li>Campos incompletos;</li>
                <li>Informações incorretas;</li>
                <li>Dados desatualizados;</li>
                <li>Classificações inconsistentes;</li>
                <li>Registros realizados de maneira diferente por cada setor;</li>
                <li>Informações que deveriam estar no sistema, mas continuam em controles externos.</li>
              </ul>

              <p>
                Dados de baixa qualidade prejudicam diretamente os indicadores. Se os dados utilizados para
                calcular um indicador estão incorretos, o resultado também será incorreto.
              </p>

              <p>
                Consequentemente, a gestão pode tomar decisões baseadas em uma realidade que não representa
                aquilo que realmente acontece na instituição.
              </p>

            </article>


