                <strong>“Qual sistema devemos comprar?”</strong>
              </p>

              <p>
                A pergunta deveria ser:
                <strong>“Qual problema precisamos resolver e qual tecnologia pode nos ajudar a resolvê-lo?”</strong>
              </p>
