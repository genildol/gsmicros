              <h2 class="entry-title">
                <a href="blog-single.html">Capacitação é parte da tecnologia</a>
              </h2>
              <p>
                Um sistema só é realmente útil quando as pessoas conseguem utilizá-lo corretamente. Por isso,
                <strong>treinamento não deve ser considerado uma etapa secundária de um projeto tecnológico</strong>.
                Ele faz parte da própria implantação.
              </p>

              <p>
                É necessário capacitar os usuários para que saibam acessar corretamente o sistema, registrar
                informações, consultar dados, corrigir erros, utilizar funcionalidades, gerar relatórios,
                seguir os fluxos estabelecidos e proteger as informações.
              </p>

              <ul>
                <li>Acesso correto ao sistema;</li>
                <li>Registro adequado das informações;</li>
                <li>Consulta e utilização dos dados;</li>
                <li>Correção de informações incorretas;</li>
                <li>Utilização das funcionalidades disponíveis;</li>
                <li>Geração e interpretação de relatórios;</li>
                <li>Segurança das informações;</li>
                <li>Respeito aos processos institucionais.</li>
              </ul>

              <p>
                Além disso, os treinamentos precisam ser contínuos. Sistemas são atualizados, processos
                mudam, novos profissionais são contratados e novas funcionalidades são incorporadas.
              </p>

            </article>

