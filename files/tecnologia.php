              <h2 class="entry-title">
                <a href="blog-single.html">Tecnologia, processos e pessoas</a>
              </h2>
              <p>
                A tecnologia representa as ferramentas, sistemas, equipamentos, infraestrutura e soluções
                digitais utilizadas pela instituição.
              </p>

              <p>
                Os processos representam os fluxos, procedimentos, responsabilidades, regras e formas de
                execução do trabalho.
              </p>

              <p>
                As pessoas representam os profissionais capacitados, a liderança, a comunicação, a cultura
                organizacional e a disposição para utilizar corretamente as ferramentas disponíveis.
              </p>

              <p>
                Se um desses três elementos falhar, a tecnologia pode não produzir os resultados esperados.
              </p>

              <ul>
                <li><strong>Tecnologia sem processo gera confusão.</strong></li>
                <li><strong>Processo sem tecnologia pode gerar limitações e excesso de trabalho manual.</strong></li>
                <li><strong>Tecnologia e processo sem pessoas preparadas também não funcionam.</strong></li>
              </ul>

              <p>
                A combinação desses três elementos é que permite uma verdadeira transformação na instituição
                de saúde.
              </p>
            </article>



