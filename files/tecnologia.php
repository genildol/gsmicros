              <h2 class="entry-title">

                <a href="blog.html">Sistemas hospitalares e a organização das informações</a>
              </h2>
              <div class="entry-content">
                <p>
                  Os sistemas de informação em saúde possuem uma função extremamente importante:
                  <strong>transformar informações espalhadas em dados organizados e utilizáveis</strong>.
                </p>

                <p>
                  Dentro de uma instituição, diferentes setores produzem informações diariamente. A recepção
                  registra pacientes, a enfermagem registra atendimentos e procedimentos, os médicos registram
                  consultas, diagnósticos e condutas, o laboratório registra exames, a farmácia controla
                  medicamentos e materiais e o faturamento utiliza informações produzidas durante o atendimento.
                </p>

                <p>
                  Quando essas informações estão integradas, a instituição consegue ter uma visão muito mais
                  clara de sua operação.
                </p>

                <p>
                  Por outro lado, quando cada setor trabalha de maneira isolada, utilizando planilhas, papéis,
                  sistemas diferentes ou controles paralelos, podem surgir inconsistências e dificuldades para
                  consolidar as informações.
                </p>


