              <h2 class="entry-title">
                <a href="blog-single.html">Sistemas precisam acompanhar os processos</a>
              </h2>
              <p>
                Outro ponto fundamental é compreender que <strong>o sistema deve apoiar o processo</strong>,
                e não simplesmente existir de forma independente.
              </p>

              <p>
                Antes de implantar uma solução tecnológica, é necessário compreender o processo que será
                informatizado.
              </p>

              <p>
                Imagine um setor que possui um processo desorganizado. Se esse processo for simplesmente
                colocado dentro de um sistema, o hospital poderá apenas transformar um processo ruim em um
                processo ruim informatizado.
              </p>

              <p>
                Por isso, antes da tecnologia, muitas vezes é necessário:
              </p>

              <ul>
                <li>Mapear o processo atual;</li>
                <li>Identificar problemas;</li>
                <li>Eliminar etapas desnecessárias;</li>
                <li>Definir responsabilidades;</li>
                <li>Padronizar procedimentos;</li>
                <li>Organizar as informações;</li>
                <li>Utilizar a tecnologia para apoiar o processo.</li>
              </ul>

              <p>
                Esse conceito é extremamente importante para qualquer projeto de transformação digital na
                área da saúde.
              </p>
            </article>



