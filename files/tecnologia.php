              <h2 class="entry-title">
                <a href="blog-single.html">A resistência dos profissionais</a>
              </h2>
              <p>
                Mesmo quando uma tecnologia é adequada, sua implantação pode enfrentar resistência. É comum
                encontrar profissionais que possuem dificuldades para abandonar métodos antigos de trabalho,
                principalmente quando já estão acostumados com determinada rotina.
              </p>

              <p>
                Frases como <strong>“sempre fizemos dessa maneira”</strong>, <strong>“esse sistema é
                  complicado”</strong> ou <strong>“prefiro fazer na planilha”</strong> podem indicar que existe
                uma barreira para a adoção correta da tecnologia.
              </p>

              <p>
                Essa resistência nem sempre significa falta de interesse. Em muitos casos, ela ocorre porque
                o profissional não recebeu treinamento suficiente ou porque a implantação não considerou
                adequadamente a realidade operacional do setor.
              </p>

              <p>
                Por isso, a implantação de tecnologia deve envolver as pessoas desde o início.
              </p>
            </article>

