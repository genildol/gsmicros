              <h2 class="entry-title">
                <a href="blog.html">O problema dos controles paralelos</a>
              </h2>

              <p>
                Um dos sinais de que uma instituição possui problemas relacionados à tecnologia é a existência
                excessiva de controles paralelos.
              </p>

              <p>
                Imagine, por exemplo, que o hospital possui um sistema oficial para registrar determinado
                processo, mas um funcionário mantém uma planilha própria porque não confia nas informações
                disponíveis no sistema. Outro setor utiliza um caderno, enquanto outro troca informações por
                mensagens.
              </p>

              <p>
                No final, existem várias versões da mesma informação. Isso gera uma pergunta fundamental:
                <strong>qual informação está correta?</strong>
              </p>

              <p>
                Quando a instituição não consegue responder isso com segurança, existe um problema de gestão
                da informação.
              </p>

              <p>
                O objetivo da tecnologia deve ser justamente reduzir esse tipo de situação, centralizando,
                organizando e disponibilizando informações confiáveis para quem precisa utilizá-las.
              </p>

            </article>

