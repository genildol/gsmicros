              <h2 class="entry-title">
                <a href="?page=blog">Qual é a diferença entre dado e informação?</a>
              </h2>
              <p>
                Embora os termos sejam frequentemente utilizados como sinônimos, existe uma diferença
                importante entre dado e informação.
              </p>

              <p>
                Um <strong>dado</strong> representa um registro ou fato que foi coletado. Uma
                <strong>informação</strong> surge quando esses dados são organizados, analisados e
                interpretados dentro de um determinado contexto.
              </p>

              <p>
                Por exemplo, imagine que um hospital registre 500 atendimentos durante determinado mês.
                O número 500 é um dado.
              </p>

              <p>
                Porém, quando esse número é comparado com os meses anteriores, com a capacidade da unidade,
                com o número de profissionais disponíveis e com o tempo médio de atendimento, ele passa a
                fornecer uma informação muito mais útil para a gestão.
              </p>

              <p>
                A pergunta deixa de ser apenas <strong>“quantos atendimentos foram realizados?”</strong>
                e passa a ser:
              </p>

              <p>
                <strong>
                  “A quantidade de atendimentos está adequada à capacidade da instituição e como esse
                  resultado se comporta em relação aos períodos anteriores?”
                </strong>
              </p>

              <p>
                É essa transformação que torna os dados realmente valiosos.
              </p>

            </article>
            <article class="entry">

              <h2 class="entry-title">
                <a href="?page=blog">A importância da qualidade dos dados</a>
              </h2>
              <p>
                Antes de produzir qualquer relatório ou indicador, é necessário garantir que os dados
                utilizados sejam confiáveis.
              </p>

              <p>
                Um relatório pode apresentar gráficos modernos, números bem organizados e uma aparência
                profissional, mas se os dados utilizados estiverem incorretos, o relatório também será
                incorreto.
              </p>

              <p>
                Alguns problemas comuns encontrados nas instituições de saúde incluem:
              </p>

              <ul>
                <li>Cadastros duplicados;</li>
                <li>Informações incompletas;</li>
                <li>Dados incorretos;</li>
                <li>Registros desatualizados;</li>
                <li>Campos preenchidos de maneiras diferentes;</li>
                <li>Informações digitadas manualmente de forma incorreta;</li>
                <li>Dados registrados em sistemas diferentes;</li>
                <li>Planilhas paralelas;</li>
                <li>Ausência de padronização;</li>
                <li>Informações que não são registradas no momento correto.</li>
              </ul>

              <p>
                Por isso, uma boa estratégia de dados precisa começar pela qualidade da informação na origem.
                Quanto melhor for o registro realizado pelos setores, maior será a qualidade dos relatórios
                produzidos posteriormente.
              </p>
            </article>

            <article class="entry">

              <h2 class="entry-title">
                <a href="?page=blog">O problema do “lixo entra, lixo sai”</a>
              </h2>
              <p>
                Existe um conceito bastante conhecido na área de dados: <strong>“lixo entra, lixo sai”</strong>.
              </p>

              <p>
                Isso significa que, quando dados incorretos são inseridos em um sistema, os resultados
                produzidos posteriormente também tendem a apresentar problemas.
              </p>

              <p>
                Imagine que uma instituição queira acompanhar o tempo médio de atendimento dos pacientes.
                Para isso, será necessário registrar corretamente os horários de chegada, atendimento,
                encaminhamento e encerramento.
              </p>

              <p>
                Se esses horários não forem registrados corretamente, o indicador calculado poderá não
                representar a realidade.
              </p>

              <p>
                Por isso, a qualidade dos relatórios começa muito antes da geração do relatório.
                Ela começa no momento em que a informação é registrada.
              </p>
            </article>

            <article class="entry">

              <h2 class="entry-title">
                <a href="?page=blog">O que são relatórios hospitalares?</a>
              </h2>
              <p>
                Relatórios hospitalares são documentos, telas ou ferramentas utilizadas para apresentar
                informações organizadas sobre determinada área, período, serviço ou processo da instituição.
              </p>

              <p>
                Um relatório pode apresentar informações operacionais, administrativas, financeiras,
                assistenciais ou estratégicas.
              </p>

              <p>
                Alguns exemplos são:
              </p>

              <ul>
                <li>Relatório de atendimentos;</li>
                <li>Relatório de internações;</li>
                <li>Relatório de altas;</li>
                <li>Relatório de ocupação de leitos;</li>
                <li>Relatório de exames;</li>
                <li>Relatório de cirurgias;</li>
                <li>Relatório de produção por setor;</li>
                <li>Relatório de faturamento;</li>
                <li>Relatório de indicadores;</li>
                <li>Relatório de desempenho;</li>
                <li>Relatório de produtividade;</li>
                <li>Relatórios gerenciais.</li>
              </ul>

              <p>
                Cada relatório deve possuir uma finalidade clara. Um relatório não deve existir simplesmente
                porque “sempre foi feito”.
              </p>

            </article>

            <article class="entry">

              <h2 class="entry-title">
                <a href="?page=blog">Um relatório precisa responder alguma pergunta</a>
              </h2>
              <p>
                Um dos principais problemas encontrados na produção de relatórios é a criação de documentos
                que apresentam muitos números, mas não ajudam efetivamente na tomada de decisão.
              </p>

              <p>
                Antes de criar um relatório, é importante perguntar:
              </p>

              <ul>
                <li>Qual pergunta esse relatório precisa responder?</li>
                <li>Quem utilizará essas informações?</li>
                <li>Qual decisão poderá ser tomada a partir delas?</li>
                <li>Qual período precisa ser analisado?</li>
                <li>Quais dados são realmente necessários?</li>
                <li>Qual indicador deve ser acompanhado?</li>
              </ul>

              <p>
                Dessa forma, o relatório deixa de ser apenas uma coleção de números e passa a ser uma
                ferramenta de gestão.
              </p>

              <h6><strong>Relatórios operacionais, gerenciais e estratégicos</strong></h6>

              <p>
                Nem todos os relatórios possuem a mesma finalidade. É possível organizar os relatórios de
                acordo com o nível de utilização da informação.
              </p>

              <p>
                Os <strong>relatórios operacionais</strong> normalmente estão relacionados às atividades
                realizadas no dia a dia.
              </p>

              <p>
                Já os <strong>relatórios gerenciais</strong> ajudam gestores e coordenadores a acompanhar
                resultados, identificar problemas e controlar o desempenho dos setores.
              </p>

              <p>
                Os <strong>relatórios estratégicos</strong> possuem uma visão mais ampla e podem ser utilizados
                pela direção para avaliar tendências, resultados gerais, investimentos, metas e planejamento
                futuro.
              </p>

              <p>
                Portanto, um mesmo dado pode ser utilizado em diferentes níveis da instituição, mas apresentado
                de maneira diferente dependendo de quem precisa utilizá-lo.
              </p>

