              <h2 class="entry-title">
                <a href="blog.html">Resistência ao uso correto dos sistemas</a>
              </h2>

              <div class="entry-content">
                <p>
                  Muitos hospitais investem em sistemas hospitalares modernos, prontuários eletrônicos e tecnologias avançadas, mas ainda enfrentam um problema muito comum: a resistência dos próprios usuários em utilizar os sistemas corretamente.
                </p>

                <p>Em várias instituições, profissionais acabam criando atalhos, ignorando funcionalidades importantes ou utilizando métodos antigos paralelamente ao sistema. Isso reduz drasticamente a eficiência da tecnologia implantada.</p>

                <p>Alguns exemplos incluem:</p>

                <ul>
                  <li>Anotações feita em papel;</li>
                  <li>Informações lançadas incompletas;</li>
                  <li>Uso incorreto de cadastros;</li>
                  <li>Compartilhamento inadequado de acesso;</li>
                  <li>Processos feitos "por fora" do sistema;</li>
                  <li>Resistência em aprender novas funções.</li>
                </ul>

                <p>Muitas vezes, essa resistência acontece por:</p>

                <ul>
                  <li>Falta de treinamento;</li>
                  <li>Medo de mudanças;</li>
                  <li>Dificuldade com tecnologia;</li>
                  <li>Sobrecarga de trabalho;</li>
                  <li>Sistemas mal implantados;</li>
                  <li>Falta de acompanhamento;</li>
                </ul>

                <P>O problema é que quando os sistemas não são utilizados corretamente, os dados ficam inconsistentes, os processos perdem eficiência e a gestão deixa de ter informações confiáveis para tomada de decisões.
                </P>
                <p>A tecnologia sozinha não resolve problemas. Ela precisa ser acompanhada de treinamento, suporte, acompanhamento operacional e conscientização das equipes.</p>
              </div>
