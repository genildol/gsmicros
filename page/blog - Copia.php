            <h2 class="entry-title">
              <a href="" class="">Saiba como se previnir de golpes na internet</a>
            </h2>

            <div class="entry-content">
              <p>
                O número de golpes na internet e fora dela tem aumentado absurdamente. Os golpes não precisam ser
                especificamente virtuais, há golpes em que pessoas caem frente a frente e ainda assim não percebem,
                muitos ainda se deixam levar por confiar em pessoas que nunca as viram.
                <!-- <strong>"Esquecem do próprio email ou da senha do email".</strong> -->
              </p>
              <p>No entanto, ao mesmo tempo que estar conectado a internet 24h por dia pode ajudar positivamente em
                diversos aspectos, sejam pessoais ou profissionais, esse contato cada vez mais profundo e ininterrupto
                com a rede cria novos tipos de ameaça e expõe usuários de diferentes formas.
              </p>
              <p>O maior problema é que muitas pessoas ainda têm pouco conhecimento a respeito de ameaças virtuais e
                ciberataques, o que eleva consideravelmente as chances de ser afetado por um. Afinal, hoje carregamos
                praticamente nossas vidas inteiras na memória do celular, por exemplo.
              </p>
              <p>As principais fraudes estão relacionadas a compras de eletrônicos, passagens aéreas, transações
                bancárias e serviços. Um em cada quatro brasileiros já foi vítima deste tipo de ação, mas é possível
                evitar essa dor de cabeça com o <a
