                  target="_blank">Serasa Antifraude</a>, um serviço que possibilita monitorar o seu CPF e evitar
                golpes.</p>
              <p>Assim como buscamos segurança em várias situações do dia-a-dia, comprar pela internet também requer
                cuidados. Confira a seguir algumas das nossas dicas para não cair nas fraudes de criminosos virtuais e
                não deixe de consultar o <a
                  href="https://www.serasa.com.br/?utm_source=serasa_ensina&utm_medium=post_fraudecompraonline&utm_campaign=serasa_consumidor"
                  target="_blank">Serasa Consumidor</a> para se precaver.</p>

              <ul>
                <li>
                  <h5><strong> 1 - Pesquise a idoneidade da empresa</strong> </h5>
                </li>
                <p>Confira os dados comerciais da empresa do comércio eletrônico. Os canais de venda virtuais são
                  obrigados a fornecer dados como razão social, endereço, telefone e CNPJ, de preferência, em sua
                  página principal, pesquise antenciosamente o site da empresa e suas redes sociais, caso tenha.
                  Desconfie de sites que não seguem essa regra.</p>

                <li>
                  <h5><strong> 2 - Indispensável não oferecer contato</strong> </h5>
                </li>
                <p>Identifique as informações de contato. Quanto mais fácil você localizar telefones, endereços e
                  e-mail para entrar em contato com o comércio eletrônico, tirar dúvidas ou encaminhar problemas, mais
                  confiável o site é e menos provável será de você ser vítima de um golpe virtual. Alguns sites,
                  inclusive, oferecem chat online pelo qual você pode conversar com um atendente em tempo real.</p>

                <li>
                  <h5><strong> 3 - Se atente as configurações de privacidade em suas contas de rede social</strong>
                  </h5>
                </li>
                <p>A maioria das redes sociais de hoje deixam por padrão seu perfil visível, isso facilita a coleta de
                  informações por pessoas mal intencionadas. As possibilidades de golpes hoje estão cada vez maiores e
                  às vezes com acesso a mínimas informações já é possível causar um estrago.</p>

                <p>Revise as configurações de suas redes sociais, altere suas senhas para uma senha muito mais forte,
                  fique atento às configurações de privacidade das suas redes e sempre revise os termos de uso quando
                  estes mudam. </p>

                <li>
                  <h5><strong> 4 - Erro de ortografia indica golpe</strong> </h5>
                </li>
                <p>Um site profissional e de grande porte terá um grande cuidado nas suas postagens, no seu conteúdo,
                  na imagem que estará transmitindo ao público. Erros de português e fotos de má qualidade são bons
                  indícios de sites que não são idôneos, construídos de forma amadora e com a finalidade exclusiva de
                  tirar dinheiro das pessoas. Preste muito atenção!</p>

                <li>
