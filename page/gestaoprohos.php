              <h2 class="entry-title" id="comunicacao">
                Comunicação entre equipes
              </h2>
              <p>A comunicação hospitalar é um dos fatores mais importantes para garantir segurança, eficiência e qualidade no atendimento.</p>


              <p>Dentro de um hospital, diversos profissionais trabalham simultaneamente:
                médicos, enfermeiros, recepcionistas, técnicos de laboratório, farmacêuticos, entre outros. A comunicação eficaz entre essas equipes é essencial para garantir que as informações sejam transmitidas de forma clara e precisa, evitando erros e garantindo a continuidade do cuidado ao paciente.</p>
              </p>
              <ul>
                <li><strong>Médicos</strong>
                  <p>Os médicos são responsáveis por diagnosticar e tratar os pacientes, além de solicitar exames e prescrever medicamentos. A comunicação entre os médicos e as equipes de enfermagem, laboratório e farmácia é fundamental para garantir que as ordens médicas sejam compreendidas e executadas corretamente.</p>
                </li>

                <li><strong>Enfermeiros</strong>
                  <p>Os enfermeiros são responsáveis por realizar o cuidado direto ao paciente, administrar medicamentos e monitorar seu estado de saúde. A comunicação eficaz entre os enfermeiros e os médicos é essencial para garantir que as ordens sejam executadas corretamente.</p>
                </li>

                <li><strong>Técnicos:</strong>
                  <p>Os técnicos de laboratório são responsáveis por realizar os exames e análises laboratoriais, fornecendo resultados precisos para auxiliar no diagnóstico e tratamento do paciente. A comunicação eficaz entre os técnicos e os médicos é essencial para garantir que os resultados sejam interpretados corretamente.</p>
                </li>

                <li><strong>Recepcionistas</strong>
                  <p>Os recepcionistas são responsáveis por receber os pacientes, registrar seus dados e direcioná-los para a triagem. A comunicação eficaz entre os recepcionistas e os médicos é essencial para garantir que os pacientes sejam atendidos de forma rápida e eficiente.</p>
                </li>

                <li><strong>Faturistas</strong>
                  <p>Os faturistas são responsáveis por realizar o faturamento dos serviços prestados, garantindo que os procedimentos sejam corretamente documentados e faturados. A comunicação eficaz entre os faturistas e os médicos é essencial para garantir que os serviços sejam adequadamente reconhecidos e remunerados.</p>
                </li>

                <li><strong>Equipe administrativa:</strong>
                  <p>A equipe administrativa é responsável por gerenciar as operações do hospital, incluindo a gestão de recursos humanos, financeiros e materiais. A comunicação eficaz entre a equipe administrativa e as demais equipes é essencial para garantir o funcionamento eficiente do hospital.</p>
                </li>

                <li><strong>TI</strong>
                  <p>A equipe de tecnologia da informação é responsável por desenvolver e manter os sistemas utilizados no hospital, garantindo que eles funcionem corretamente e atendam às necessidades das equipes de saúde. A comunicação eficaz entre a equipe de TI e as demais equipes é essencial para garantir o sucesso dos projetos tecnológicos.</p>
                </li>
                <li><strong>Regulação</strong>
                  <p>A regulação é responsável por estabelecer e manter os padrões de qualidade e segurança no hospital, garantindo que as práticas sejam conformes com as normas e regulamentações aplicáveis.</p>
                </li>
                <li><strong>Farmácia</strong>
                  <p>A equipe de farmácia é responsável por gerenciar o estoque de medicamentos, garantir a distribuição adequada e manter os padrões de qualidade e segurança nos processos farmacêuticos.</p>
                </li>
                <li><strong>UTI</strong>
                  <p>A unidade de terapia intensiva é responsável por fornecer cuidados avançados e monitoramento constante para pacientes em estado crítico. A comunicação eficaz entre a equipe da UTI e as demais equipes é essencial para garantir a continuidade do cuidado e a coordenação de tratamentos.</p>
                </li>
                <li><strong>Terapeutas e fisioterapeutas</strong>
                  <p>A equipe de terapeutas e fisioterapeutas é responsável por fornecer cuidados especializados para pacientes em recuperação. A comunicação eficaz entre a equipe de terapeutas e as demais equipes é essencial para garantir a continuidade do cuidado e a coordenação de tratamentos.</p>
                </li>
                <p>Todos precisam trocar informações constantemente.</p>

                <h6><strong>Problemas causados por falha na comunicação</strong></h6>
                <p>Quando a comunicação é ruim:</p>
              </ul>

              <ul>
                <li>Informações se perdem</li>
